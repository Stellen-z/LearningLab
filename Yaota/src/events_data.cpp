const EventDef& eventDef(int id) {
    for (const auto& e : eventDex())
        if (e.id == id) return e;
    return eventDex().front();
}

const EventDef& randomEvent(int floor) {
    std::vector<int> pool;
    for (const auto& e : eventDex())
        if (floor >= e.minFloor) pool.push_back(e.id);
    return eventDef(Rng::get().pick(pool));
}

